type MessageCatalog = typeof messages.en;

interface I18nContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  messages: MessageCatalog;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({children}: {children: ReactNode}) {
  const [language, setLanguage] = useState<AppLanguage>(() => {
    const saved = window.localStorage.getItem('delta-spend-language');
    return saved === 'zh' ? 'zh' : 'en';
  });

  useEffect(() => {
    window.localStorage.setItem('delta-spend-language', language);
  }, [language]);

  const value = useMemo(
    () => ({language, setLanguage, messages: messages[language]}),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside I18nProvider');
  }
  return context;
}
